#!/usr/bin/env node
/**
 * THE CLI'S OWN COPY OF THE CREDENTIAL PATTERNS.
 *
 * Redaction must never depend on an input that can be swapped. Until a fix every redaction took
 * `baseline-002` from the LOADED bundle, and a bundle is whatever `--bundle` or `LEGAL_BUNDLE_DIR` names: a
 * bundle without `baseline-002` turned the redaction of the report, the exports and findings.json off without a
 * word. The CLI now carries the rule's compile input itself, in `product/packages/cli/src/credential-rule.generated.ts`,
 * and every redaction compiles that copy, whatever bundle runs.
 *
 * ONE ORIGINAL, EXPORTED AND IMPORTED. The rule source (`rules/packs/baseline/baseline-002`) stays the only original;
 * this file is the export. `build-bundle.mjs` calls `credentialCopyProblem` on the rules it has just built from the
 * real rule tree and fails the build where the CLI's copy differs, naming the command that rewrites it:
 *
 *   node tools/credential-rule-copy.mjs --write      (after `npm run build:bundle` has built dist/bundle)
 *
 * The copy holds the rule's id, pack and detector exactly as `dist/bundle/rules.json` carries them (shared
 * vocabulary already merged), so `compileRules` compiles it exactly as the scan compiles the bundle's rule.
 */
import { fileURLToPath } from "node:url";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
export const CREDENTIAL_COPY_PATH = join(ROOT, "product/packages/cli/src/credential-rule.generated.ts");
const RULE_ID = "baseline-002";

/** A JSON text with every character outside printable ASCII written as an escape (the source-text lint). */
const asciiJson = (value) =>
  JSON.stringify(value, null, 2).replace(/[^\x20-\x7e\n]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);

/** The generated module's text for one rule list (the bundle's rules, as written to rules.json). */
export function credentialCopyText(rules) {
  const rule = rules.find((r) => r.id === RULE_ID);
  if (!rule) throw new Error(`credential-rule-copy: no ${RULE_ID} in the rule list`);
  const copy = { id: rule.id, pack: rule.pack, detector: rule.detector };
  return (
    `/**\n` +
    ` * GENERATED by tools/credential-rule-copy.mjs from ${RULE_ID} as the bundle build writes it to rules.json. Do not\n` +
    ` * edit: change the rule, build the bundle, then run \`node tools/credential-rule-copy.mjs --write\`. The bundle\n` +
    ` * build fails while this copy differs from the rule.\n` +
    ` *\n` +
    ` * The CLI's own credential patterns: every redaction compiles this copy, whatever bundle a run loads, so no\n` +
    ` * bundle can turn redaction off or change it.\n` +
    ` */\n` +
    `import type { Rule } from "wolfboy-schemas";\n\n` +
    `export const PRODUCT_CREDENTIAL_RULE = ${asciiJson(copy)} as unknown as Rule;\n`
  );
}

/** Null where the CLI's copy is the one `rules` produce; else one sentence naming what to run. */
export function credentialCopyProblem(rules) {
  const want = credentialCopyText(rules);
  const have = existsSync(CREDENTIAL_COPY_PATH) ? readFileSync(CREDENTIAL_COPY_PATH, "utf8") : null;
  if (have === want) return null;
  return (
    `the CLI's own copy of ${RULE_ID}'s patterns (product/packages/cli/src/credential-rule.generated.ts) ` +
    `${have === null ? "is missing" : "differs from the rule just built"}: every redaction compiles that copy, so a ` +
    `changed rule would detect with one set of patterns and redact with another. Run ` +
    `\`node tools/credential-rule-copy.mjs --write\` after this build, rebuild the CLI, and commit the file.`
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const from = join(ROOT, "dist/bundle/rules.json");
  const rules = JSON.parse(readFileSync(from, "utf8"));
  if (process.argv.includes("--write")) {
    writeFileSync(CREDENTIAL_COPY_PATH, credentialCopyText(rules));
    console.log(`wrote ${CREDENTIAL_COPY_PATH.slice(ROOT.length)} from ${from.slice(ROOT.length)}`);
  } else {
    const problem = credentialCopyProblem(rules);
    console.log(problem ?? "the CLI's copy of baseline-002 matches dist/bundle/rules.json");
    process.exit(problem ? 1 : 0);
  }
}
