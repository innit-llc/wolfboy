#!/usr/bin/env node
/**
 * Generate `src/identity.generated.ts`, the program's name, version and address as its package.json states them, and
 * check it.
 *
 * WHY. The SARIF file named its tool `product-cli`, version
 * 0.1.0, at https://example.invalid, three values typed into sarif.ts beside the same three typed into index.ts
 * (`program.name`, `.version`) and the package's own manifest. A code-scanning alert is keyed by the tool's name, so the
 * name a team first uploads under must be the package's, and a rename must reach every place at once.
 *
 * ONE SOURCE. The CLI's package.json stays the only original: `bin`'s one name is the program's name, `version` its
 * version, `homepage` its address. The generated module holds them, checked, not trusted: the CLI's build
 * (`npm run build`, `--check`) fails while it differs, naming the command that regenerates it. The module is compiled in,
 * so a copy of `dist/` alone carries it, as it carries the schemas (scripts/schemas-module.mjs).
 *
 * Usage: node scripts/identity-module.mjs [--write | --check]   (default --check; exit 1 on a difference)
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const PKG = join(dirname(fileURLToPath(import.meta.url)), "..");
/** The one source. */
export const IDENTITY_SOURCE = join(PKG, "package.json");
/** The generated module, compiled with the rest of the CLI. */
export const IDENTITY_MODULE = join(PKG, "src", "identity.generated.ts");
/** What regenerates it, as the refusal names it. */
export const IDENTITY_MODULE_COMMAND = "node product/packages/cli/scripts/identity-module.mjs --write";

/** The three values, from package.json; throws where one is missing or `bin` names more than one program. */
export function identityOf(path = IDENTITY_SOURCE) {
  const pkg = JSON.parse(readFileSync(path, "utf8"));
  const bins = typeof pkg.bin === "string" ? [pkg.name] : Object.keys(pkg.bin ?? {});
  if (bins.length !== 1) throw new Error(`identity-module: ${path} must name exactly one program in "bin" (found ${bins.length})`);
  for (const field of ["version", "homepage"]) {
    if (typeof pkg[field] !== "string" || pkg[field] === "") throw new Error(`identity-module: ${path} has no "${field}"`);
  }
  return { name: bins[0], version: pkg.version, homepage: pkg.homepage };
}

/** The generated module's text. */
export function identityModuleText(path = IDENTITY_SOURCE) {
  const id = identityOf(path);
  return (
    `/**\n` +
    ` * GENERATED by product/packages/cli/scripts/identity-module.mjs from product/packages/cli/package.json, the one source.\n` +
    ` * Do not edit: change package.json, run \`${IDENTITY_MODULE_COMMAND}\`, and commit this file. The CLI's\n` +
    ` * build fails while it differs from package.json.\n` +
    ` */\n` +
    `/** The program's name: the one name package.json's "bin" gives it (the SARIF tool's name, which keys its alerts). */\n` +
    `export const PROGRAM_NAME = ${JSON.stringify(id.name)};\n` +
    `/** The program's version: package.json's "version". */\n` +
    `export const PROGRAM_VERSION = ${JSON.stringify(id.version)};\n` +
    `/** The program's address: package.json's "homepage". */\n` +
    `export const PROGRAM_HOMEPAGE = ${JSON.stringify(id.homepage)};\n`
  );
}

/** Null where `modulePath` is the module package.json produces; else one sentence naming the fix. */
export function identityModuleProblem({ path = IDENTITY_SOURCE, modulePath = IDENTITY_MODULE } = {}) {
  const want = identityModuleText(path);
  const have = existsSync(modulePath) ? readFileSync(modulePath, "utf8") : null;
  if (have === want) return null;
  const where = relative(process.cwd(), modulePath) || modulePath;
  return (
    `the CLI's compiled-in name, version and address (${where}) ${have === null ? "are missing" : "are not package.json's"}. ` +
    `Run \`${IDENTITY_MODULE_COMMAND}\`, rebuild the CLI, and commit the file.`
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes("--write")) {
    writeFileSync(IDENTITY_MODULE, identityModuleText());
    console.error(`identity-module: wrote ${IDENTITY_MODULE}`);
  } else {
    const problem = identityModuleProblem();
    if (problem) {
      console.error(`identity-module: ${problem}`);
      process.exit(1);
    }
    // stderr, not stdout: `npm pack --json` prints its JSON on stdout after the prepack scripts.
    console.error("identity-module: the compiled-in name, version and address match package.json");
  }
}
