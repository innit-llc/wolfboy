#!/usr/bin/env node
/**
 * Generate `src/schemas.generated.ts`, the JSON Schemas as part of the CLI's own compiled code, and check it.
 *
 * WHY. From 2026-10-12 the CLI read its schemas at run time from `schemas/` beside
 * its `dist/`, a folder only `scripts/copy-schemas.mjs` wrote, as the last step of this package's `npm run build`; later
 * it fell back to the workspace's `product/packages/schemas/schemas`. Anything that built the CLI any other
 * way, or copied `dist/` elsewhere, got a program that could not validate what it read and wrote, and that broke seven
 * times: four gates and two test drivers on 2026-10-12, and the rule-diff sweep's private copy of the CLI on
 * 2026-10-13. The fallback was an instance fix. With the schemas compiled in, `tsc -b` alone, `npm run build`, the
 * packed package and any copy of `dist/` all carry them, and no file beside the program is read for them.
 *
 * ONE SOURCE. The schemas package's `schemas/*.schema.json` stay the only original. The generated module holds each
 * file's exact text, so it is checked, not trusted: the CLI's own build (`npm run build`, `--check`) and the bundle
 * build (`tools/build-bundle.mjs`) fail while it differs from those files, naming the command that regenerates it.
 *
 * Usage: node scripts/schemas-module.mjs [--write | --check]   (default --check; exit 1 on a difference)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const PKG = join(dirname(fileURLToPath(import.meta.url)), "..");
/** The one source: the schemas package's own files. */
export const SCHEMAS_SOURCE = join(PKG, "..", "schemas", "schemas");
/** The generated module, compiled with the rest of the CLI. */
export const SCHEMAS_MODULE = join(PKG, "src", "schemas.generated.ts");
/** What regenerates it, as the refusal names it. */
export const SCHEMAS_MODULE_COMMAND = "node product/packages/cli/scripts/schemas-module.mjs --write";

/** A JSON string literal with every character outside printable ASCII written as an escape (the source-text lint). */
const asciiString = (text) =>
  JSON.stringify(text).replace(/[^\x20-\x7e]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);

/** The schema files of a folder, by name, each with its exact text. */
export function schemaFilesOf(dir = SCHEMAS_SOURCE) {
  const names = readdirSync(dir).filter((n) => n.endsWith(".schema.json")).sort();
  return names.map((name) => ({ name, text: readFileSync(join(dir, name), "utf8") }));
}

/** The generated module's text for the schema files of `dir`. */
export function schemasModuleText(dir = SCHEMAS_SOURCE) {
  const files = schemaFilesOf(dir);
  if (files.length === 0) throw new Error(`schemas-module: no *.schema.json under ${dir}`);
  return (
    `/**\n` +
    ` * GENERATED by product/packages/cli/scripts/schemas-module.mjs from product/packages/schemas/schemas/*.schema.json,\n` +
    ` * the one source. Do not edit: change the schema, run \`${SCHEMAS_MODULE_COMMAND}\`, and commit\n` +
    ` * this file. The CLI's build and the bundle build fail while it differs from the schemas.\n` +
    ` *\n` +
    ` * The JSON Schemas this program validates against, as part of its own compiled code: every way of building the CLI\n` +
    ` * and every copy of its dist/ carries them, so no folder beside the program and no workspace behind it is read for\n` +
    ` * them. Each value is the file's exact text (characters outside ASCII written as escapes), so the digest of a schema\n` +
    ` * taken here is the file's own digest.\n` +
    ` */\n` +
    `export const SCHEMA_TEXTS: Readonly<Record<string, string>> = {\n` +
    files.map((f) => `  ${JSON.stringify(f.name)}:\n    ${asciiString(f.text)},\n`).join("") +
    `};\n`
  );
}

/**
 * Null where `modulePath` is the module the schema files of `dir` produce; else one sentence naming the schemas that
 * differ and the command that regenerates the module.
 */
export function schemasModuleProblem({ dir = SCHEMAS_SOURCE, modulePath = SCHEMAS_MODULE } = {}) {
  const want = schemasModuleText(dir);
  const have = existsSync(modulePath) ? readFileSync(modulePath, "utf8") : null;
  if (have === want) return null;
  const where = relative(process.cwd(), modulePath) || modulePath;
  if (have === null) return `the CLI's compiled-in schemas (${where}) are missing. Run \`${SCHEMAS_MODULE_COMMAND}\`, rebuild the CLI, and commit the file.`;
  const files = schemaFilesOf(dir);
  const stale = files.filter((f) => !have.includes(`${JSON.stringify(f.name)}:\n    ${asciiString(f.text)},\n`)).map((f) => f.name);
  const named = new Set(files.map((f) => f.name));
  const extra = [...have.matchAll(/^ {2}("[^"\n]+\.schema\.json"):$/gm)].map((m) => JSON.parse(m[1])).filter((n) => !named.has(n));
  const what = [
    stale.length > 0 ? `${stale.length} schema(s) differ from their file or are absent (${stale.join(", ")})` : "",
    extra.length > 0 ? `${extra.length} schema(s) no longer have a file (${extra.join(", ")})` : "",
  ].filter(Boolean);
  return (
    `the CLI's compiled-in schemas (${where}) are not the schema files of ${relative(process.cwd(), dir) || dir}: ` +
    `${what.length > 0 ? what.join("; ") : "the module's text differs"}. The program would validate against other ` +
    `schemas than the ones in the repository. Run \`${SCHEMAS_MODULE_COMMAND}\`, rebuild the CLI, and commit the file.`
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes("--write")) {
    writeFileSync(SCHEMAS_MODULE, schemasModuleText());
    console.error(`schemas-module: wrote ${SCHEMAS_MODULE} from ${schemaFilesOf().length} schemas`);
  } else {
    const problem = schemasModuleProblem();
    if (problem) {
      console.error(`schemas-module: ${problem}`);
      process.exit(1);
    }
    // stderr, not stdout: `npm pack --json` prints its JSON on stdout after the prepack scripts.
    console.error(`schemas-module: the compiled-in schemas match the ${schemaFilesOf().length} schema files`);
  }
}
